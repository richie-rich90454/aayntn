/**
 * The aayntn laboratory core.
 *
 * An algorithm and its animation are deliberately separated:
 *
 *   1. A trusted TypeScript reference implementation produces a list of
 *      `LabEvent` values. It knows nothing about SVG, Vue or the DOM.
 *   2. A *scene* renders a `LabState` into SVG markup. It knows nothing about
 *      which algorithm produced the state.
 *   3. The player controls playback, scrubbing, speed, custom input and the
 *      narration panel.
 *
 * The separation has two consequences that matter:
 *
 *   - The animation cannot drift away from the mathematics, because it is
 *     generated by the same code that computes the answer.
 *   - Every scene is a pure function, so the visual behavior can be tested
 *     in Node without a browser.
 */

export type LabNodeState =
    | "unvisited"
    | "discovered"
    | "active"
    | "completed"
    | "invalid"
    | "selected";

export type LabEdgeState = "idle" | "active" | "done" | "invalid" | "tree";

export type LabCellState = "idle" | "active" | "done" | "highlight" | "invalid";

export interface LabNode {
    id: string;
    label: string;
    x?: number;
    y?: number;
    state?: LabNodeState;
    value?: string;
    sublabel?: string;
    /** Extra shape hint: 'square' for a decision node, 'circle' by default. */
    shape?: "circle" | "square" | "diamond";
    /** Non-color cue so state is never encoded by color alone. */
    marker?: string;
}

export interface LabEdge {
    from: string;
    to: string;
    label?: string;
    state?: LabEdgeState;
    directed?: boolean;
    /** Curvature, used to keep parallel edges apart. */
    curve?: number;
    /** Non-color cue. */
    marker?: string;
}

export interface LabCell {
    index: number;
    value: string;
    state?: LabCellState;
    /** Inclusive index range this cell is responsible for. */
    range?: [number, number];
    /** Additional text drawn under the value. */
    sublabel?: string;
}

export interface LabStructure {
    id: string;
    label: string;
    kind: "stack" | "queue" | "heap" | "set" | "list" | "priority-queue";
    items: { value: string; state?: LabCellState; sublabel?: string }[];
    /** Orientation hint for stack and queue rendering. */
    orientation?: "vertical" | "horizontal";
}

export interface LabTable {
    rowLabels: string[];
    colLabels: string[];
    cells: {
        row: number;
        col: number;
        value: string;
        state?: LabCellState;
        dependsOn?: [number, number][];
    }[];
}

export interface LabAnnotation {
    x: number;
    y: number;
    text: string;
    emphasis?: "normal" | "accent" | "error";
    /** Anchor for the text. */
    anchor?: "start" | "middle" | "end";
}

export interface LabAxis {
    min: number;
    max: number;
    label?: string;
    /** Marks the currently active position. */
    cursor?: number;
}

/**
 * The complete visual state of a laboratory at one point in time.
 */
export interface LabState {
    nodes: LabNode[];
    edges: LabEdge[];
    cells: LabCell[];
    structures: LabStructure[];
    table?: LabTable;
    annotations: LabAnnotation[];
    axis?: LabAxis;
    /** Scene-specific extras (bar heights, tree depths, and so on). */
    data: Record<string, unknown>;
    /** The mathematical expression shown next to the picture, if any. */
    formula?: string;
}

export function emptyState(): LabState {
    return {
        nodes: [],
        edges: [],
        cells: [],
        structures: [],
        annotations: [],
        data: {},
    };
}

/**
 * An algorithm event.
 *
 * `operation` is a *semantic* identifier such as `relax-edge`. Source
 * implementations map their own regions to these identifiers, which is how a
 * single visualization stays synchronized with six implementations whose
 * line numbers and control flow all differ.
 */
export interface LabEvent {
    type: string;
    operation?: string;
    /** One sentence, present tense, describing what just changed. */
    narration: string;
    /** The state after the event was applied. */
    state: LabState;
}

export interface LabPreset {
    id: string;
    label: string;
    /** Raw input text, editable by the reader. */
    input: string;
}

export interface LabDefinition {
    id: string;
    title: string;
    /** Scene renderer id. */
    scene: string;
    description: string;
    presets: LabPreset[];
    /** Build the event stream for a given preset. */
    build: (preset: LabPreset) => LabEvent[];
    /** Extra guidance shown next to the controls. */
    notes?: string[];
    /** Maximum number of characters the custom input may contain. */
    maxInputLength?: number;
}

/* ------------------------------------------------------------------ */
/* Scene rendering                                                     */
/* ------------------------------------------------------------------ */

export interface RenderOptions {
    width: number;
    height: number;
    /** Show the annotations layer. */
    showAnnotations: boolean;
    /** Show the implementation panel. */
    showImplementation: boolean;
}

export interface LabScene {
    id: string;
    /** The SVG viewBox for the scene. */
    viewBox: (options: RenderOptions) => string;
    /** Render the state to SVG markup. */
    render: (state: LabState, options: RenderOptions) => string;
}
